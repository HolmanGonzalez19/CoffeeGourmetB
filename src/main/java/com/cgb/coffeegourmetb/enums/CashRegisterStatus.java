package com.cgb.coffeegourmetb.enums;

/**
 * Estados posibles de una caja registradora.
 */
public enum CashRegisterStatus {

    /**
     * La caja se encuentra actualmente abierta y operativa.
     */
    ABIERTA,

    /**
     * La caja fue cerrada y ya no acepta nuevas operaciones.
     */
    CERRADA
}